"""Shows statement and branch coverage of the two white-box functions, step by step.

Each step runs a growing set of white-box tests under coverage.py and prints the
coverage of calculate_deposit() and validate_party_size() only.

    python white_box/white_box_report.py          (from 05_Test_Automation/)

Results are also saved to 06_Test_Reports/white_box/White_Box_Coverage_Results.md
"""
import json
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
SUITE = HERE.parent
ROOT = SUITE.parent
APP = ROOT / "application" / "reservation_system"
OUT = ROOT / "06_Test_Reports" / "white_box" / "White_Box_Coverage_Results.md"

FUNCTIONS = ["calculate_deposit", "validate_party_size"]
# (label, which tests to run, which functions to show)
STEPS = [
    ("TC-WB-01 only", "WB_01", ["calculate_deposit"]),
    ("TC-WB-01 + TC-WB-02", "WB_01 or WB_02", ["calculate_deposit"]),
    ("TC-WB-03 only", "WB_03", ["validate_party_size"]),
    ("TC-WB-03 + 04 + 05", "WB_03 or WB_04 or WB_05", ["validate_party_size"]),
    ("All white-box tests (WB-01 to WB-06)", "WB_", FUNCTIONS),
]


def measure(selection):
    with tempfile.TemporaryDirectory() as tmp:
        report = Path(tmp) / "cov.json"
        cmd = [sys.executable, "-m", "pytest", str(HERE), "-q", "-p", "no:cacheprovider", "-k", selection,
               f"--cov={APP}", "--cov-branch", f"--cov-report=json:{report}"]
        proc = subprocess.run(cmd, cwd=SUITE, capture_output=True, text=True)
        if proc.returncode != 0:
            print(proc.stdout[-2000:])
            sys.exit("White-box tests failed.")
        data = json.loads(report.read_text())
    result = {}
    for file in data["files"].values():
        for name in FUNCTIONS:
            if name in file.get("functions", {}):
                s = file["functions"][name]["summary"]
                result[name] = (f"{s['covered_lines']}/{s['num_statements']}", s["percent_statements_covered"],
                                f"{s['covered_branches']}/{s['num_branches']}", s["percent_branches_covered"])
    return result


def main():
    rows = []
    print(f"\n{'Tests run':<40}{'Function':<22}{'Statements':>16}{'Branches':>16}")
    print("-" * 94)
    for label, selection, shown in STEPS:
        res = measure(selection)
        for name in shown:
            st, sp, br, bp = res[name]
            print(f"{label:<40}{name + '()':<22}{st + f'  {sp:5.0f}%':>16}{br + f'  {bp:5.0f}%':>16}")
            rows.append(f"| {label} | `{name}()` | {st} ({sp:.0f}%) | {br} ({bp:.0f}%) |")
    print()

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "# White-Box Coverage Results\n\n"
        "Generated by `05_Test_Automation/white_box/white_box_report.py` using coverage.py "
        "(statement + branch coverage, measured per function).\n\n"
        "| Tests run | Function | Statement coverage | Branch coverage |\n|---|---|---|---|\n"
        + "\n".join(rows) +
        "\n\n**Key observation:** TC-WB-01 alone runs every statement of `calculate_deposit()` "
        "(100% statement coverage) but takes only half of the branch outcomes (50% branch coverage). "
        "Adding TC-WB-02 takes the False side of both decisions, giving 100% branch coverage. "
        "This is why branch coverage is a stronger criterion than statement coverage.\n",
        encoding="utf-8")
    print(f"Saved: {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
